/** The examples in a group, in library order. */
export function libraryGroups(): { group: LibraryExample['group']; examples: LibraryExample[] }[] {
  const groups: { group: LibraryExample['group']; examples: LibraryExample[] }[] = []
  for (const example of LIBRARY) {
    let entry = groups.find(g => g.group === example.group)
    if (!entry) groups.push(entry = { group: example.group, examples: [] })
    entry.examples.push(example)
  }
  return groups
}
