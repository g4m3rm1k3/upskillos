// The CodeLens learning library: examples to load, step through, change and compare across
// languages. Each example says what it teaches, what to watch while stepping, its
// complexity and invariants where they matter, edge cases to try, and exercises; each
// language variant has the output it prints (library.test.ts runs every variant this
// machine can run and checks that output).
//
// Variants are the same program in each language, written the way that language is
// normally written (a Python swap is `a, b = b, a`; C# sorts with a for loop the same way
// but prints with string.Join), so comparing them teaches the differences that matter.
// C# and C++ run in the desktop app only.
import type { Lang } from './types'
import { SNIPPET_CATEGORIES } from './snippets'
import { LEARNING_EXAMPLES } from './learningExamples'

export type Difficulty = 'Beginner' | 'Intermediate' | 'Advanced'

export interface LibraryVariant {
  code: string
  /** What the program prints, line by line, as CodeLens shows it (with `input`, if any). */
  output: string[]
  /** What goes in the Input box (scriptedInput.ts): the lines the program reads, and for
   *  pygame programs the scripted keys and clicks. Loaded with the code. */
  input?: string
}

export interface LibraryExample {
  id: string
  title: string
  group: 'Data Structures' | 'Algorithms' | 'Design Patterns' | 'Functional Programming' | 'Input and Games' | 'Reinforcement Learning' | 'React Internals'
  difficulty: Difficulty
  /** What the example teaches, in a few sentences. */
  concept: string
  prerequisites: string[]
  /** What to look at while stepping through it. */
  watch: string[]
  /** Reviewed by hand: CodeLens doesn't infer complexity. */
  complexity?: string
  /** Facts that stay true at every step; checking them is how you know the code is right. */
  invariants?: string[]
  edgeCases?: string[]
  exercises: string[]
  variants: Partial<Record<Lang, LibraryVariant>>
}

export const LANGUAGE_LABELS: Record<Lang, string> = {
  js: 'JavaScript', ts: 'TypeScript', py: 'Python', cs: 'C#', cpp: 'C++', c: 'C', go: 'Go',
}

// The original JavaScript snippets, for examples that only exist in JavaScript.
function snippet(name: string): string {
  for (const category of SNIPPET_CATEGORIES) {
    const found = category.items.find(item => item.name === name)
    if (found) return found.code
  }
  throw new Error(`No snippet named ${name}`)
}

