// @vitest-environment jsdom
import React from 'react'
import { render, fireEvent, cleanup, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import LessonExperience from './LessonExperience'
import { lessons, sequenceByIds } from './registry'
import { defineLesson, validateSequence } from './schema'
import { choose } from './runtime'
import pascal, { selections } from './lessons/pascal'

afterEach(() => { cleanup(); vi.restoreAllMocks() })
function mount(id) {
  const lesson = lessons.find(item => item.id === id)
  const view = render(<LessonExperience lesson={lesson} />)
  const root = view.container.querySelector('section')
  return { ...view, root, query: selector => root.querySelector(selector), explanation: () => root.querySelector('.wm-explanation').textContent }
}
const input = (node, value) => fireEvent.input(node, { target: { value: String(value) } })

describe('standalone lesson contract', () => {
  it.each(lessons.map(lesson => [lesson.id, lesson.title]))('%s mounts independently: %s', id => {
    const { root, query } = mount(id)
    expect(root.querySelectorAll('.wm-panel')).toHaveLength(4)
    for (const key of ['observation','why','tryNext']) expect(query(`[data-state="${key}"]`).textContent.length).toBeGreaterThan(20)
    const ids = [...root.querySelectorAll('[id]')].map(node => node.id)
    expect(new Set(ids).size).toBe(ids.length)
    expect(root.querySelector('.wm-panel:nth-child(2)').textContent.trim().length).toBeGreaterThan(0)
  })
  it('accepts a contributor file and rejects malformed or repeated entries', () => {
    const custom = {...lessons[0], id:'new-contributor-lesson', order:42}
    expect(defineLesson(custom).schemaVersion).toBe(1)
    expect(() => defineLesson({...custom, panels:{scene:'<svg/>'}})).toThrow('panel markup')
    expect(() => defineLesson({...custom, mount:null})).toThrow('mount')
    expect(() => validateSequence([custom,custom])).toThrow('Duplicate')
    expect(sequenceByIds(['l14','l1']).map(x=>x.id)).toEqual(['l14','l1'])
    expect(() => sequenceByIds(['missing'])).toThrow('Unknown')
  })
  it('does not share state between two instances of the same lesson', () => {
    const lesson = lessons[0]
    const { container } = render(<><LessonExperience lesson={lesson}/><LessonExperience lesson={lesson}/></>)
    const [a,b] = container.querySelectorAll('section')
    fireEvent.click(a.querySelector('#ad'))
    expect(a.querySelector('#num').textContent).toBe('1')
    expect(b.querySelector('#num').textContent).toBe('0')
  })
})

