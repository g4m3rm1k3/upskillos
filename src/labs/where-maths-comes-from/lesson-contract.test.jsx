describe('Pascal entries mean actual choices', () => {
  it('shows the single empty and complete selections at the two edges', () => {
    const {root,query,explanation}=mount('l6')
    fireEvent.click(query('[data-reveal=pattern-view]'))
    fireEvent.click(within(root).getByRole('button',{name:'The edges'}))
    expect(explanation()).toContain('one way to leave every object out')
    expect(query('#choice-examples').textContent).toContain('Empty selection')
    fireEvent.click(query('#choose-all'))
    expect(explanation()).toContain('one way to include every object')
    expect(query('#choice-examples').textContent).toContain('A · B · C · D')
    fireEvent.click(query('#choice-add'))
    expect(query('#choice-count').textContent).toContain('1 different selection')
    expect(query('#choice-examples').textContent).toContain('E')
  })
  it('shows the two disjoint parent groups and updates from direct object selection', () => {
    const {root,query,explanation}=mount('l6')
    fireEvent.click(query('[data-reveal=pattern-view]'))
    const entry=within(root).getByRole('button',{name:'Row 4, position 2: 6'})
    entry.focus();fireEvent.keyDown(entry,{key:'Enter'})
    expect(explanation()).toContain('3 selections leave it out; 3 include it')
    expect(query('#choice-examples').children).toHaveLength(6)
    expect(document.activeElement.getAttribute('data-r')).toBe('4')
    fireEvent.click(query('[data-object="2"]'))
    expect(query('#choice-heading').textContent).toContain('choose 3')
    expect(explanation()).toContain('counts 4 ways')
  })
  it('explains diagonals, doubling, and odd-count parity for the current state', () => {
    const {query,explanation}=mount('l6')
    fireEvent.click(query('[data-reveal=pattern-view]'))
    fireEvent.click(query('[data-p="d1"]'));expect(explanation()).toContain('new single-object selection')
    fireEvent.click(query('[data-p="d2"]'));expect(explanation()).toContain('same growth as handshakes')
    fireEvent.click(query('[data-p="sum"]'));expect(explanation()).toContain('16 possibilities')
    fireEvent.click(query('[data-p="odd"]'));expect(explanation()).toContain('one odd parent and one even parent')
    input(query('#prow'),16)
    expect(query('#choice-examples').children.length).toBeLessThanOrEqual(12)
  })
  it('enumeration agrees with the exact binomial count, including empty and full selections', () => {
    for(let n=0;n<=8;n++)for(let k=0;k<=n;k++){
      const actual=selections(n,k,300)
      expect(actual).toHaveLength(choose(n,k))
      expect(new Set(actual.map(x=>x.join(','))).size).toBe(actual.length)
      for(const picked of actual)expect(picked).toHaveLength(k)
    }
    expect(selections(15,7)).toHaveLength(12)
    expect(pascal.id).toBe('l6')
  })
})


