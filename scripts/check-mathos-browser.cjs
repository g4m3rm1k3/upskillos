// Run against an existing Vite/preview server. Artifacts stay in ignored .cache.
const { chromium, expect } = require('playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const output = path.resolve('.cache/mathos-verification');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  page.setDefaultTimeout(60000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(process.argv[2] || 'http://127.0.0.1:5187', { waitUntil: 'domcontentloaded', timeout: 120000 });
    await page.waitForFunction(() => typeof window.__openMathOS === 'function');
    const skip = page.getByRole('button', { name: 'Skip', exact: true });
    await skip.click({ timeout: 20000 });
    await page.evaluate(() => window.__openMathOS());
    const workspace = page.getByRole('dialog', { name: 'MathOS workspace' });
    await expect(workspace).toBeVisible();
    await workspace.getByRole('button', { name: 'Data & models', exact: true }).click();
    await workspace.getByRole('button', { name: 'Preview table', exact: true }).click();
    await workspace.getByRole('button', { name: 'Use this table', exact: true }).click();
    await expect(workspace.getByRole('img', { name: /Scatter plot/ })).toBeVisible();
    await workspace.getByRole('button', { name: 'Fit linear model', exact: true }).click();
    await expect(workspace.getByText(/Held-out RMSE: 0/)).toBeVisible();
    await workspace.getByLabel('Row 1, measurement', { exact: true }).fill('2');
    await expect(workspace.getByRole('button', { name: 'Export model JSON', exact: true })).toHaveCount(0);
    await workspace.getByRole('button', { name: 'Fit linear model', exact: true }).click();
    const predictionsDownload = page.waitForEvent('download');
    await workspace.getByRole('button', { name: 'Export predictions CSV', exact: true }).click();
    await (await predictionsDownload).saveAs(path.join(output, 'predictions.csv'));
    await page.screenshot({ path: path.join(output, 'data-desktop.png') });
    page.once('dialog', dialog => dialog.accept());
    await workspace.getByRole('button', { name: 'Use table in JavaScript', exact: true }).click();
    await workspace.getByRole('button', { name: '▶ Run', exact: true }).click();
    await expect(workspace.locator('pre').filter({ hasText: 'measurement' })).toBeVisible();
    await workspace.getByRole('button', { name: /Compute/, exact: false }).click();
    const bounds = await workspace.boundingBox();
    if (bounds.x !== 0 || bounds.y !== 0 || bounds.width !== 1440 || bounds.height !== 960) throw new Error('MathOS did not fill the viewport');
    const expression = workspace.getByLabel('What would you like to calculate?');
    await expression.fill('2^10');
    await expression.press('Enter');
    await expect(workspace.getByRole('status', { name: 'Calculation result' })).toContainText('1024');
    await workspace.getByText('Projects, programming & machine learning', { exact: true }).click();
    await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
    await workspace.getByRole('button', { name: 'Copy project', exact: true }).click();
    await expect(workspace.getByText('Project copied as JSON.', { exact: true })).toBeVisible();
    await expression.fill('123');
    page.on('dialog', dialog => dialog.accept());
    await workspace.getByRole('button', { name: 'Paste project', exact: true }).click();
    await expect(expression).toHaveValue('2^10');
    const exported = page.waitForEvent('download');
    await workspace.getByRole('button', { name: 'Export project', exact: true }).click();
    const file = path.join(output, 'mathos-project.json');
    await (await exported).saveAs(file);
    if (JSON.parse(fs.readFileSync(file, 'utf8')).dataset.rows[0][1] !== '2') throw new Error('Project lost edited dataset');
    await workspace.getByRole('button', { name: 'Load ML example', exact: true }).click();
    await workspace.getByRole('button', { name: '▶ Run', exact: true }).click();
    await expect(workspace.locator('pre').filter({ hasText: 'Held-out MSE:' })).toBeVisible();
    await workspace.getByText('Projects, programming & machine learning', { exact: true }).click();
    await workspace.getByLabel('Import MathOS project').setInputFiles(file);
    await expect(workspace.getByText('Project imported. Programs are ready to inspect and run.')).toBeVisible();
    await expect(expression).toHaveValue('2^10');
    await workspace.getByText('Projects, programming & machine learning', { exact: true }).click();
    await workspace.getByRole('button', { name: 'History & tools', exact: true }).click();
    await expect(workspace.getByRole('region', { name: 'Calculation history' })).toContainText('2^10');
    await expression.fill('3+4');
    await expression.press('Enter');
    await workspace.getByRole('region', { name: 'Calculation history' }).getByRole('button', { name: /2\^10/ }).click();
    await expect(expression).toHaveValue('2^10');
    await expect(workspace.getByRole('status', { name: 'Calculation result' })).toContainText('1024');
    await workspace.getByRole('button', { name: 'Restore MathOS window' }).click();
    const restored = await workspace.boundingBox();
    if (restored.width >= 1440 || restored.height >= 960) throw new Error('Restore did not shrink the window');
    await workspace.getByRole('button', { name: 'DEG', exact: true }).or(workspace.getByRole('button', { name: 'RAD', exact: true })).click();
    const afterMode = await workspace.boundingBox();
    if (afterMode.x !== restored.x || afterMode.y !== restored.y) throw new Error('Titlebar button moved the window');
    await workspace.getByRole('button', { name: 'Maximize MathOS' }).click();
    await page.screenshot({ path: path.join(output, 'desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(expression).toHaveValue('2^10');
    await workspace.getByRole('button', { name: 'Variables', exact: true }).click();
    await expect(expression).not.toBeVisible();
    await workspace.getByRole('button', { name: 'Workspace', exact: true }).click();
    await expect(expression).toBeVisible();
    await workspace.getByRole('button', { name: 'History & tools', exact: true }).click();
    await workspace.getByRole('region', { name: 'Calculation history' }).getByRole('button', { name: /3\+4/ }).click();
    await expect(expression).toHaveValue('3+4');
    for (const locator of [workspace, expression, workspace.getByRole('button', { name: 'Compute', exact: true })]) {
      const box = await locator.boundingBox();
      if (!box || box.x < 0 || box.x + box.width > 391) throw new Error('Mobile controls overflow');
    }
    await page.screenshot({ path: path.join(output, 'mobile.png') });
    await workspace.getByLabel('MathOS tool', { exact: true }).selectOption('data');
    await expect(workspace.getByLabel('Row 1, measurement', { exact: true })).toHaveValue('2');
    await page.screenshot({ path: path.join(output, 'data-mobile.png') });
    await workspace.getByLabel('MathOS tool', { exact: true }).selectOption('graph');
    await workspace.getByLabel('xMin', { exact: true }).fill('10');
    await expect(workspace.getByRole('alert')).toContainText('Graph bounds must be finite');
    await workspace.getByRole('button', { name: 'reset bounds', exact: true }).click();
    await expect(workspace.getByRole('alert')).toHaveCount(0);
    await workspace.getByRole('button', { name: 'Close MathOS' }).click();
    await expect(workspace).toHaveCount(0);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => typeof window.__openMathOS === 'function');
    await page.evaluate(() => window.__openMathOS());
    await workspace.getByRole('button', { name: 'History & tools', exact: true }).click();
    await expect(workspace.getByRole('region', { name: 'Calculation history' })).toContainText('2^10');
    await workspace.getByText('Projects, programming & machine learning', { exact: true }).click();
    await workspace.getByRole('button', { name: 'Machine Learning Lab', exact: true }).click();
    await expect(workspace).toHaveCount(0);
    await expect(page.getByRole('heading', { name: /^Machine Learning Lab/, level: 1 })).toBeVisible();
    if (errors.length) throw new Error(errors.join('\n'));
    console.log('PASS: editable dataset, scatter plot, regression, stale-fit invalidation, prediction export, dataset project round-trip, fullscreen, calculations, history, clipboard, executable ML, mobile layout, graph recovery, close, no page errors.');
  } catch (error) {
    console.error((await page.locator('body').innerText()).slice(-5000));
    await page.screenshot({ path: path.join(output, 'failure.png') });
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
